export const WHEEL_SEGMENT_COUNT = 12;
export const DISPLAY_COUNT = 20;
export const TOTAL_ENTRIES = 151;

export function maskNumber(num) {
	if (!num) return '';
	const parts = num.split(' ');
	if (parts.length < 4) return num;
	return `${parts[0]} ${parts[1]} *** ${parts[3].slice(0, 2)}**`;
}

export function maskWinner(num) {
	if (!num) return '';
	const parts = num.split(' ');
	if (parts.length < 4) return num;
	return `${parts[0]} ${parts[1]} ${parts[2]} ****`;
}

export function buildPrizes(nums) {
	return nums.slice(0, WHEEL_SEGMENT_COUNT).map((num, i) => ({
		label: maskNumber(num),
		backgroundColor: i % 2 === 0 ? '#FAAA32' : '#FFC857',
		labelColor: '#4D4D4D',
	}));
}
